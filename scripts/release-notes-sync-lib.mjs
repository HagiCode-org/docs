let releaseNotesMarkdownProcessorPromise;

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function assertNonEmptyString(value, fieldName) {
  assert(
    typeof value === 'string' && value.trim().length > 0,
    `Invalid release-notes payload: ${fieldName} must be a non-empty string`,
  );
  return value.trim();
}

function toPosixPath(value) {
  return value.split(path.sep).join('/');
}

function relativeFromRepo(repoRoot, absolutePath) {
  return toPosixPath(path.relative(repoRoot, absolutePath));
}

function ensureJsonResponse(response, context) {
  if (!response?.ok) {
    const detail =
      response?.status === 404
        ? ' Check the repository slug and provide a token with access to the upstream release-notes repository.'
        : '';
    throw new Error(`${context} failed with status ${response?.status ?? 'unknown'}.${detail}`);
  }

  const contentType = response.headers?.get?.('content-type') ?? '';
  if (!contentType.toLowerCase().includes('application/json')) {
    throw new Error(`${context} expected application/json but received ${contentType || 'unknown content-type'}`);
  }
}

function escapeYamlString(value) {
  return JSON.stringify(value ?? '');
}

function stripLeadingHeading(markdown) {
  const trimmed = markdown.replace(/^\uFEFF/, '');
  return trimmed.replace(/^# .+\n+(?=\S)/u, '');
}

async function getReleaseNotesMarkdownProcessor() {
  if (!releaseNotesMarkdownProcessorPromise) {
    releaseNotesMarkdownProcessorPromise = createMarkdownProcessor();
  }

  return releaseNotesMarkdownProcessorPromise;
}

async function renderLandingBodyHtml(markdown) {
  const processor = await getReleaseNotesMarkdownProcessor();
  const bodyMarkdown = stripLeadingHeading(markdown).trim();
  const rendered = await processor.render(bodyMarkdown);
  return rendered.code.trim();
}

function normalizeDateOnly(value) {
  if (typeof value !== 'string' || value.trim().length === 0) {
    return null;
  }

  const trimmed = value.trim();
  if (/^\d{4}-\d{2}-\d{2}$/u.test(trimmed)) {
    return trimmed;
  }

  const parsed = new Date(trimmed);
  if (Number.isNaN(parsed.getTime())) {
    return null;
  }

  return parsed.toISOString().slice(0, 10);
}

// Counts the Features and Fixes entries of a published body and lists its repository headings in order.
// Entries are the `- ` bullets under `## Features` or `## Fixes`; repositories are the `### ` headings.
function parseReleaseBody(markdown) {
  let section = null;
  const counts = { features: 0, fixes: 0 };
  const repositories = [];

  for (const rawLine of markdown.split('\n')) {
    const line = rawLine.trim();
    const heading = /^(#{1,6})\s+(.*\S)\s*$/u.exec(line);
    if (heading) {
      const level = heading[1].length;
      const text = heading[2].trim();
      if (level === 2) {
        section = text === 'Features' ? 'features' : text === 'Fixes' ? 'fixes' : null;
      } else if (level === 3 && !repositories.includes(text)) {
        repositories.push(text);
      }
      continue;
    }

    if (section && /^[-*+]\s+\S/u.test(line)) {
      counts[section] += 1;
    }
  }

  return { ...counts, repositories };
}

// Summary rule (deterministic, English, one string per tag):
// "<n> features and <m> fixes across <repository>, <repository>." Zero-count kinds are omitted.
export function createReleaseSummary({ features, fixes, repositories }) {
  const parts = [];
  if (features > 0) {
    parts.push(`${features} ${features === 1 ? 'feature' : 'features'}`);
  }
  if (fixes > 0) {
    parts.push(`${fixes} ${fixes === 1 ? 'fix' : 'fixes'}`);
  }

  const scope = repositories.length > 0 ? ` across ${repositories.join(', ')}` : '';
  return `${parts.join(' and ')}${scope}.`;
}

function getReleaseNoteDetailFileName(tag) {
  return `${assertNonEmptyString(tag, 'tag')}.json`;
}

function buildReleaseSortValue(tag) {
  const normalized = tag.startsWith('v') ? tag.slice(1) : tag;
  const valid = semver.valid(normalized);

  return valid ?? normalized;
}

export function normalizeReleaseNotesAnchorId(tag) {
  const trimmedTag = assertNonEmptyString(tag, 'tag');
  const normalizedTag = trimmedTag.replace(/^v+/iu, '').toLowerCase();
  return `v${normalizedTag}`;
}

function compareReleaseEntries(left, right) {
  const leftSortVersion = left.sortVersion ?? left.tag;
  const rightSortVersion = right.sortVersion ?? right.tag;
  const semverComparison = semver.valid(leftSortVersion) && semver.valid(rightSortVersion)
    ? semver.rcompare(leftSortVersion, rightSortVersion)
    : 0;

  if (semverComparison !== 0) {
    return semverComparison;
  }

  const leftPublishedAt = left.publishedAt ?? '';
  const rightPublishedAt = right.publishedAt ?? '';
  if (leftPublishedAt !== rightPublishedAt) {
    return rightPublishedAt.localeCompare(leftPublishedAt);
  }

  return right.tag.localeCompare(left.tag, 'en', { numeric: true, sensitivity: 'base' });
}

function createGitHubHeaders({ token, accept }) {
  return {
    accept,
    'user-agent': 'hagicode-docs-release-notes-sync',
    ...(token ? { authorization: `Bearer ${token}` } : {}),
  };
}

function runCommand(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd,
    env: options.env ? { ...process.env, ...options.env } : process.env,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  if (result.error) {
    throw result.error;
  }

  if ((result.status ?? 0) !== 0) {
    const detail = [result.stderr, result.stdout].filter(Boolean).join('\n').trim();
    throw new Error(
      `${command} ${args.join(' ')} failed with exit code ${result.status}${detail ? `: ${detail}` : ''}`,
    );
  }

  return {
    stdout: result.stdout ?? '',
    stderr: result.stderr ?? '',
    status: result.status ?? 0,
  };
}

function listZipEntries(zipPath) {
  return runCommand('unzip', ['-Z1', zipPath]).stdout
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .filter((entry) => !entry.endsWith('/'));
}

function readZipEntryText(zipPath, entryPath) {
  return runCommand('unzip', ['-p', zipPath, entryPath]).stdout.replace(/\r\n/g, '\n');
}

// The drafter capture has no timestamp, so the release date comes only from the GitHub Release
// (`published_at`). Local sources without a release date show no date.
function normalizeCaptureRepositories(payload) {
  return payload.repositories
    .filter(isRecord)
    .filter((row) => row.status === 'ok')
    .map((row) => {
      const lastTag = typeof row.lastTag === 'string' ? row.lastTag : null;
      const endTag = typeof row.endTag === 'string' ? row.endTag : null;
      return {
        repository: typeof row.key === 'string' ? row.key : '',
        path: typeof row.input === 'string' ? row.input : '',
        label: typeof row.name === 'string' ? row.name : '',
        fromTag: lastTag,
        toTag: endTag,
        range: lastTag && endTag ? `${lastTag}..${endTag}` : null,
        commitCount: row.commitCount,
        renderedCount: row.renderedCount,
        truncated: row.truncated === true,
      };
    })
    .sort((left, right) => left.repository.localeCompare(right.repository));
}

function normalizeAcceptedReleaseNote({ accepted, synchronizedAt }) {
  const repositoryRanges = normalizeCaptureRepositories(accepted.payload);
  const body = parseReleaseBody(accepted.body);

  return {
    tag: accepted.tag,
    displayTag: accepted.tag,
    sortVersion: buildReleaseSortValue(accepted.tag),
    releaseDate: normalizeDateOnly(accepted.candidate.releasePublishedAt),
    publishedAt: accepted.candidate.releasePublishedAt ?? null,
    synchronizedAt,
    upstreamGeneratedAt: null,
    anchorId: normalizeReleaseNotesAnchorId(accepted.tag),
    summary: createReleaseSummary({
      features: body.features,
      fixes: body.fixes,
      repositories: body.repositories,
    }),
    repositoryRanges: repositoryRanges.map((entry) => ({
      repository: entry.repository,
      path: entry.path,
      label: entry.label,
      fromTag: entry.fromTag,
      toTag: entry.toTag,
      range: entry.range,
      commitCount: entry.commitCount,
      renderedCount: entry.renderedCount,
      truncated: entry.truncated,
    })),
    totalCommitCount: repositoryRanges.reduce((sum, entry) => sum + entry.commitCount, 0),
    source: {
      releaseName: accepted.candidate.releaseName,
      releaseUrl: accepted.candidate.releaseHtmlUrl,
      assetName: accepted.candidate.assetName,
      assetUrl: accepted.candidate.assetDownloadUrl,
      capturePath: accepted.capturePath,
      bodyPath: accepted.bodyPath,
    },
    body: accepted.body,
  };
}

